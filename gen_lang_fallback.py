#!/usr/bin/env python3
"""Regenerate static/lang/<lang>.js from static/lang/<lang>.json for EVERY language.

The .js dictionaries are used when the UI is opened straight from disk (file://, the demo
mode of static/index.html), where fetch() of JSON is blocked. Before, only bg.js existed, so
the demo was Bulgarian whatever language was chosen. Run after editing any lang/*.json.
"""
import json, pathlib

root = pathlib.Path(__file__).parent / 'static' / 'lang'
for src in sorted(root.glob('*.json')):
    lang = src.stem
    data = json.loads(src.read_text(encoding='utf8'))
    body = json.dumps(data, ensure_ascii=False, indent=1)
    (root / f'{lang}.js').write_text(
        f'// generated by gen_lang_fallback.py from {lang}.json - do not edit\n'
        f'window.__I18N = window.__I18N || {{}}; window.__I18N[{json.dumps(lang)}] = ' + body + ';\n',
        encoding='utf8')
    print('wrote', root / f'{lang}.js')
