// i18n — lightweight translation loader for Diabet Logger
//
// Load this script SYNCHRONOUSLY (no `defer`/`async`) before any page code that calls t().
// Page init code should `await i18nReady()` before it renders anything, so text is never
// generated while the dictionary is still empty. After a language switch a `langchange`
// event is dispatched on `document`; pages listen to it to re-render dynamic text.
// Directory this script was loaded from, so it also works when the page is opened from disk.
const _base = (document.currentScript && document.currentScript.src)
  ? document.currentScript.src.replace(/[^/]*$/, '') : '/static/';
let _lang = localStorage.getItem('diabet_lang') || navigator.language.slice(0, 2) || 'bg';
let _strings = {};
let _i18nReady = null;
const _supported = {
  bg: '🇧🇬 Български',
  en: '🇬🇧 English',
  de: '🇩🇪 Deutsch',
  es: '🇪🇸 Español',
  fr: '🇫🇷 Français',
  'pt-PT': '🇵🇹 Português',
  'pt-BR': '🇧🇷 Português (Brasil)',
  it: '🇮🇹 Italiano',
  nl: '🇳🇱 Nederlands',
  pl: '🇵🇱 Polski'
};

const _domReady = document.readyState !== 'loading'
  ? Promise.resolve()
  : new Promise(res => document.addEventListener('DOMContentLoaded', res, { once: true }));

// file:// (demo mode): fetch() of local JSON is blocked, so load lang/<lang>.js instead.
// One <lang>.js per language is generated by gen_lang_fallback.py (bg is the fallback).
function _loadScriptDict(lang) {
  return new Promise((resolve, reject) => {
    const s = document.createElement('script');
    s.src = _base + 'lang/' + lang + '.js';
    s.onload = () => (window.__I18N && window.__I18N[lang]) ? resolve(window.__I18N[lang]) : reject(new Error('empty'));
    s.onerror = () => reject(new Error('missing ' + lang + '.js'));
    document.head.appendChild(s);
  });
}

async function _fetchStrings(lang) {
  if (location.protocol === 'file:') return _loadScriptDict(lang);
  const res = await fetch(_base + 'lang/' + lang + '.json?v=' + Date.now());
  if (!res.ok) throw new Error(res.statusText);
  return res.json();
}

async function loadLang(lang) {
  if (!(lang in _supported)) lang = 'bg';
  let strings;
  try {
    strings = await _fetchStrings(lang);
  } catch (e) {
    console.warn('[i18n] failed to load ' + lang + ':', e);
    if (lang === 'bg') return;           // nothing left to fall back to; t() returns keys
    return loadLang('bg');
  }
  _strings = strings;
  _lang = lang;
  try { localStorage.setItem('diabet_lang', lang); } catch (e) {}
  await _domReady;                       // never apply before the markup exists
  applyTranslations();
  document.documentElement.lang = lang;
  const sel = document.getElementById('lang-select');
  if (sel) sel.value = lang;
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

// Resolves once the first dictionary is loaded and applied. Safe to call many times.
function i18nReady() {
  if (!_i18nReady) _i18nReady = loadLang(_lang);
  return _i18nReady;
}

function t(key, params) {
  let s = _strings[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), v);
    }
  }
  return s;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = _strings[el.getAttribute('data-i18n')];
    if (val) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const val = _strings[el.getAttribute('data-i18n-html')];
    if (val) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const val = _strings[el.getAttribute('data-i18n-placeholder')];
    if (val) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const val = _strings[el.getAttribute('data-i18n-title')];
    if (val) el.title = val;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const val = _strings[el.getAttribute('data-i18n-aria')];
    if (val) el.setAttribute('aria-label', val);
  });
}

function setLang(lang) { _i18nReady = loadLang(lang); return _i18nReady; }

function buildLangSelector() {
  const sel = document.getElementById('lang-select');
  if (!sel) return;
  sel.innerHTML = '';
  for (const [code, name] of Object.entries(_supported)) {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = name;
    sel.appendChild(opt);
  }
  sel.value = _lang;
  sel.addEventListener('change', () => setLang(sel.value));
}

_domReady.then(buildLangSelector);
i18nReady();   // start fetching the dictionary immediately

// ---------- shared: readable API error text ----------
// Server errors come as {"detail": "..."} (400/404/502) or, for 422,
// {"detail": [{msg, loc, ...}], "message": "..."}. Never show raw JSON to the user.
function apiErrorText(status, bodyText) {
  try {
    const j = JSON.parse(bodyText);
    if (j && typeof j.message === 'string' && j.message) return j.message;
    if (j && typeof j.detail === 'string') return j.detail;
    if (j && Array.isArray(j.detail) && j.detail[0]) {
      return String(j.detail[0].msg || '').replace(/^Value error, /, '') || ('HTTP ' + status);
    }
  } catch (_) { /* not JSON */ }
  const txt = String(bodyText || '').trim();
  return txt ? `${status}: ${txt.slice(0, 200)}` : ('HTTP ' + status);
}

// BG entered in mg/dL by habit (> 30 can't be mmol/L): offer the conversion,
// never convert silently. Returns the value to use, or null to abort.
function bgMgdlGuard(v) {
  if (!(v > 30)) return v;
  const mmol = Math.round(v / 18 * 10) / 10;
  return confirm(t('confirm_bg_mgdl', { v, mmol })) ? mmol : null;
}

// ---------- shared: 401 handling (P1/B1) ----------
// Any 401 means every credential we sent was rejected (the server tries the
// API key first, then the JWT). So: drop BOTH stored credentials, tell the user
// plainly that the last action was NOT saved, and offer the right way back in —
// the login form in login mode, the key prompt in api-key mode. Never silent.
async function onUnauthorized() {
  try { localStorage.removeItem('diabet_token'); localStorage.removeItem('diabet_api_key'); } catch (_) {}
  let mode = 'login';
  try {
    const h = await (await fetch('/api/health')).json();
    mode = h.auth.login ? 'login' : (h.auth.api_key ? 'apikey' : 'open');
  } catch (_) { /* offline: assume login */ }
  showAuthBanner(mode);
  if (mode === 'login' && typeof showLogin === 'function') showLogin();
}

function showAuthBanner(mode) {
  let b = document.getElementById('auth-banner');
  if (!b) {
    b = document.createElement('div');
    b.id = 'auth-banner';
    b.setAttribute('role', 'alert');
    b.style.cssText = 'position:fixed;top:0;left:0;right:0;z-index:10000;background:#b3261e;color:#fff;' +
      'padding:10px 14px;font:14px/1.4 system-ui,sans-serif;display:flex;gap:10px;align-items:center;flex-wrap:wrap';
    document.body.prepend(b);
  }
  b.innerHTML = '';
  const msg = document.createElement('span');
  msg.style.flex = '1';
  msg.textContent = t(mode === 'apikey' ? 'auth_bad_key' : 'auth_expired');
  b.appendChild(msg);
  const btn = document.createElement('button');
  btn.style.cssText = 'background:#fff;color:#b3261e;border:0;border-radius:6px;padding:6px 12px;font-weight:600;cursor:pointer';
  if (mode === 'apikey') {
    btn.textContent = t('auth_enter_key');
    btn.onclick = () => {
      const k = prompt(t('prompt_api_key'), '');
      if (k === null || !k.trim()) return;
      try { localStorage.setItem('diabet_api_key', k.trim()); } catch (_) {}
      location.reload();
    };
  } else if (typeof showLogin === 'function') {
    btn.textContent = t('login');
    btn.onclick = () => showLogin();
  } else {
    btn.textContent = t('login');               // page without a login form (profiles, cgm_view)
    btn.onclick = () => { location.href = '/'; };
  }
  b.appendChild(btn);
}

function hideAuthBanner() {
  const b = document.getElementById('auth-banner');
  if (b) b.remove();
}
